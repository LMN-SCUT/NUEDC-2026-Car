void TIM2_IRQHandler(void)
{    
    static uint16_t cnt_10ms = 0;
    static uint16_t cnt_100ms = 0;

    if(TIM_GetITStatus(TIM2, TIM_IT_Update) != RESET)
    {
        
        cnt_10ms++;
        cnt_100ms++;
       

        // 10ms MPU¸üÐÂ
        if(cnt_10ms >= 10)
        {
            cnt_10ms = 0;
            mpu_flag = 1;
        }

        // 100ms OLEDË¢ÐÂ
        if(cnt_100ms >= 100)
        {
            cnt_100ms = 0;
            oled_flag = 1;
        }

        TIM_ClearITPendingBit(TIM2, TIM_IT_Update);
    }
}